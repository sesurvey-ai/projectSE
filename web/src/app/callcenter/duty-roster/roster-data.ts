// ── คำนวณสถานะจากเวลา/ข้อความ ─────────────────────────
export function deriveStatus(t: string): Status {
  const v = (t || '').trim();
  if (!v) return 'pending';                 // ยังไม่เข้างาน / ไม่มีข้อมูล
  if (v.includes('ลาป่วย') || v.includes('ลา')) return 'leave';
  if (v.includes('วันหยุด') || v === 'หยุด') return 'off';
  if (v.includes('ระวัง')) return 'watch';
  if (/\d/.test(v)) return 'present';       // มีเวลา = เข้างานแล้ว
  return 'pending';
}

