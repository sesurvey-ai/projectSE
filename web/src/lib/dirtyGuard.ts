let dirty = false;

export const setFormDirty = (v: boolean) => { dirty = v; };
export const isFormDirty = () => dirty;

/** true = ไปต่อได้ (ไม่มีอะไรค้าง หรือคนยืนยันแล้วว่ายอมให้หาย) */
export const confirmLeaveIfDirty = (
  msg = 'ออกจากหน้านี้?' + String.fromCharCode(10)
      + 'สิ่งที่แก้ค้างไว้แต่ยังไม่ได้กด "บันทึกร่าง" จะหายทั้งหมด',
) => !dirty || window.confirm(msg);
