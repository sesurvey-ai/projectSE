/**
 * ตัวเลือกสำหรับเคสหนึ่ง ๆ — ค่าเดิมที่ไม่อยู่ในลิสต์ EMCS ให้พ่วงไว้หัวลิสต์
 * ⛔ ห้ามตัดทิ้ง: งานเก่ามีชื่อสะกดนอกลิสต์อยู่จริง ถ้าไม่พ่วงไว้ select จะเด้ง
 *    เป็นค่าว่าง แล้วกดบันทึกทีเดียวชื่อประกันหายทั้งช่อง
 *    (ผู้ตรวจต้องเลือกใหม่ให้ตรงลิสต์ EMCS ก่อนอนุมัติ — ดูป้ายเตือนข้างช่อง)
 */
export const insurerOptions = (current: string): string[] => {
  const c = String(current ?? '').trim();
  return c && !INSURER_COMPANY_OPTIONS.includes(c)
    ? [c, ...INSURER_COMPANY_OPTIONS]
    : INSURER_COMPANY_OPTIONS;
};

/** ชื่อนี้เลือกบน EMCS ได้จริงไหม — ใช้ทาแดงเตือนผู้ตรวจ */
export const isEmcsInsurer = (v: string): boolean =>
  !String(v ?? '').trim() || INSURER_COMPANY_OPTIONS.includes(String(v).trim());
