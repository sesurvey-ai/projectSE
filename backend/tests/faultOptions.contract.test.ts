/**
 * การ์ดของ "ฝ่ายประมาท" (หมวด 5) — user สั่งแก้ 31/08/69
 *
 *   1. ป้ายบนจอ "คู่กรณีผิด" → "รถประกันฝ่ายถูก" (เรียกจากมุมรถประกันให้เหมือนตัวเลือกอื่น)
 *   2. เลือก "รถประกันฝ่ายถูก" หรือ "ฝ่ายถูกและผิด" → บังคับติ๊ก "การเรียกร้องค่าเสียหายจากคู่กรณี"
 *
 * ⛔ **หัวใจของไฟล์นี้: ป้ายเปลี่ยนได้ แต่ค่าที่บันทึกห้ามเปลี่ยน**
 *    ค่า `'คู่กรณีผิด'` ไหลตรงไปเป็น radio ของ EMCS (CAUSE_RADIO → rdoAcc_Cause01),
 *    เป็นรหัสผลคดีในไฟล์ XML, และเป็นตัวเปิดเงื่อนไขบังคับทุกที่ที่เรียก _faultIs()
 *    ถ้าใครเผลอแก้ key ตอนอยากแก้คำบนจอ: ของเก่า 4 ค่าในฐานข้อมูลจะกลายเป็นค่าที่
 *    ไม่มีใครรู้จัก และบอทจะกรอกผลคดี **ผิดฝ่ายทั้งสำนวน** โดยไม่มี error ที่ไหนเลย
 */
import * as fs from 'fs';
import * as path from 'path';

let failed = 0;
const check = (label: string, ok: boolean, note = '') => {
  if (!ok) failed++;
  console.log(`  [${ok ? 'PASS' : 'FAIL'}] ${label}${note ? `  (${note})` : ''}`);
};
const read = (...p: string[]) => fs.readFileSync(path.join(__dirname, '..', ...p), 'utf8');

const form = read('..', 'mobile', 'lib', 'screens', 'survey_form_screen.dart');
const web = read('..', 'web', 'src', 'components', 'cases', 'CaseDetail.tsx');
const xmlOut = read('src', 'services', 'xmlExport.service.ts');

console.log('\n── ป้ายบนจอ vs ค่าที่บันทึก ──');
check('ป้ายในแอปเป็น "รถประกันฝ่ายถูก"', /'คู่กรณีผิด': 'รถประกันฝ่ายถูก'/.test(form));
/** ⛔ อย่าแก้ key — ดูเหตุผลหัวไฟล์ */
check('ค่าที่บันทึกยังเป็น \'คู่กรณีผิด\' เหมือนเดิม (ห้ามเปลี่ยน)',
      /'คู่กรณีผิด':/.test(form) && !/'รถประกันฝ่ายถูก':/.test(form));
check('ปลายทาง XML ยังรู้จักค่านี้', /'คู่กรณีผิด': '2'/.test(xmlOut));
/** เว็บ checker จงใจใช้คำของ EMCS ("รถคู่กรณีเป็นฝ่ายผิด") — แต่ value ต้องตรงกับแอป */
check('เว็บส่ง value เดียวกับแอป', /name="acc_fault" value="คู่กรณีผิด"/.test(web));

console.log('\n── บังคับติ๊ก "การเรียกร้องค่าเสียหายจากคู่กรณี" ──');
/**
 * ⛔ เงื่อนไข "มีคู่กรณี" ของเดิมต้องอยู่ครบ ห้ามแทนที่ด้วยเงื่อนไขผลคดีอย่างเดียว —
 *    กติกานั้นเพิ่งแก้ไป 22/08/69 เพราะงานที่รถประกันผิดหลุดไปไม่มีค่านี้ทุกใบ
 *    (เดิมบังคับเฉพาะตอนคู่กรณีผิด) ถอยกลับเมื่อไหร่ = หัวหน้าต้องมาเติมเองอีกรอบ
 */
const cond = /_opponents\.isNotEmpty \|\| _faultIs\('คู่กรณีผิด'\) \|\| _faultIs\('ฝ่ายถูกและผิด'\)/g;
const hits = form.match(cond) || [];
check('เงื่อนไขบังคับครบ 3 ทาง (มีคู่กรณี / รถประกันฝ่ายถูก / ฝ่ายถูกและผิด)', hits.length >= 1);
/** จุดแดงกับตัวตรวจก่อนส่งต้องใช้เงื่อนไขเดียวกัน ไม่งั้นช่างเจอ "ไม่ผ่าน" โดยไม่รู้ว่าช่องไหน */
check('จุดแดงบนหัวข้อใช้เงื่อนไขเดียวกับตัวตรวจก่อนส่ง', hits.length === 2,
      `เจอ ${hits.length} ที่ (ต้องเป็น 2: ตัวตรวจ + จุดแดง)`);
check('หัวข้อรับ req เข้าไปจริง',
      /_fieldLabel\('การเรียกร้องค่าเสียหายจากคู่กรณี', req: claimRequired\)/.test(form));

console.log('\n── ของเดิมที่ต้องไม่พังตาม ──');
/** "คู่กรณีคันที่" ผูกกับ 'คู่กรณีผิด' อย่างเดียว — ฝ่ายถูกและผิดไม่ต้องระบุคัน */
check('"คู่กรณีคันที่" ยังบังคับเฉพาะตอนคู่กรณีผิด',
      /if \(_faultIs\('คู่กรณีผิด'\)\)\s*\n\s*_numField\(_accFaultOpponentNoCtl/.test(form));
/** ตาข่ายรับค่าเก่าในฐานข้อมูล ('รถคู่กรณีเป็นฝ่ายผิด' มีจริง 1 ใบ) ต้องยังอยู่ */
check('ยังรับสำเนียงเก่าของค่าเดิมได้', /'คู่กรณีผิด': \['รถคู่กรณีเป็นฝ่ายผิด'\]/.test(form));
check('ตำรวจยังบังคับเฉพาะ "รอสรุปผลคดี"', /_faultIs\('รอสรุปผลคดี'\)/.test(form));

console.log(failed === 0 ? '\n✅ ผ่านทั้งหมด' : `\n❌ ไม่ผ่าน ${failed} ข้อ`);
process.exit(failed === 0 ? 0 : 1);
