/**
 * การ์ดของ "ฝ่ายประมาท" (หมวด 5) — user สั่งแก้ 31/08/69
 *
 *   เลือก "คู่กรณีผิด" หรือ "ฝ่ายถูกและผิด" → บังคับติ๊ก "การเรียกร้องค่าเสียหายจากคู่กรณี"
 *
 * ⛔ **ตัวเลือกชุดนี้ต้องตรงกับที่อยู่บน EMCS** — user ลองเปลี่ยนคำเป็น "รถประกันฝ่ายถูก"
 *    แล้วถอยกลับเองในวันเดียวกัน เพราะหัวหน้าต้องเทียบหน้าจอต่อหน้าจอตอนตรวจ
 *    (เป็นเรื่องเดียวกันคนละมุมมองก็จริง แต่คำต้องตรง) — อย่าเสนอเปลี่ยนคำซ้ำ
 *
 * ⛔ **และค่าที่บันทึกยิ่งห้ามเปลี่ยน**
 *    ค่า `'คู่กรณีผิด'` ไหลตรงไปเป็น radio ของ EMCS (CAUSE_RADIO → rdoAcc_Cause01),
 *    เป็นรหัสผลคดีในไฟล์ XML, และเป็นตัวเปิดเงื่อนไขบังคับทุกที่ที่เรียก _faultIs()
 *    ถ้าใครเผลอแก้ key ตอนอยากแก้คำบนจอ: ของเก่า 4 ค่าในฐานข้อมูลจะกลายเป็นค่าที่
 *    ไม่มีใครรู้จัก และบอทจะกรอกผลคดี **ผิดฝ่ายทั้งสำนวน** โดยไม่มี error ที่ไหนเลย
 */
import * as fs from 'fs';
import * as path from 'path';

let failed = 0;
const check = (label: string, ok: boolean, note = '') => {
  if (!ok) failed++;
  console.log(`  [${ok ? 'PASS' : 'FAIL'}] ${label}${note ? `  (${note})` : ''}`);
};
const read = (...p: string[]) => fs.readFileSync(path.join(__dirname, '..', ...p), 'utf8');

const form = read('..', 'mobile', 'lib', 'screens', 'survey_form_screen.dart');
const web = read('..', 'web', 'src', 'components', 'cases', 'CaseDetail.tsx');
const xmlOut = read('src', 'services', 'xmlExport.service.ts');

console.log('\n── ตัวเลือกต้องตรงกับ EMCS ──');
/** ⛔ ทั้งป้ายและค่าต้องเป็น 'คู่กรณีผิด' — ดูเหตุผลหัวไฟล์ */
check('ป้ายในแอปตรงกับคำบน EMCS ("คู่กรณีผิด")', /'คู่กรณีผิด': 'คู่กรณีผิด'/.test(form));
check('ไม่มีคำว่า "รถประกันฝ่ายถูก" หลงเหลือในตัวเลือก', !/'รถประกันฝ่ายถูก'/.test(form));
check('ปลายทาง XML ยังรู้จักค่านี้', /'คู่กรณีผิด': '2'/.test(xmlOut));
/** เว็บ checker จงใจใช้คำของ EMCS ("รถคู่กรณีเป็นฝ่ายผิด") — แต่ value ต้องตรงกับแอป */
check('เว็บส่ง value เดียวกับแอป', /name="acc_fault" value="คู่กรณีผิด"/.test(web));

console.log('\n── บังคับติ๊ก "การเรียกร้องค่าเสียหายจากคู่กรณี" ──');
/**
 * ⛔ **ผูกกับผลคดี 2 ค่าเท่านั้น ห้ามใส่เงื่อนไข "มีคู่กรณี" กลับเข้าไป**
 *    user สั่ง 31/08/69 หลังเจอตอนเทสกรอกจริง: เลือก "รถประกันฝ่ายผิด" แล้วยังโดนบังคับ
 *    เพราะกรอกคู่กรณีไว้ในหมวด 6 → กลับกติกา 22/08/69 ที่บังคับ "มีคู่กรณี → ต้องติ๊กเสมอ"
 *
 *    ของเดิมกว้างกว่าที่ EMCS บังคับจริงด้วย — บอทหยุดรอเฉพาะตอนผลคดี = คู่กรณีผิด
 *    (rdoAcc_Cause01) เท่านั้น ค่าอื่นติ๊กหรือไม่ติ๊กก็บันทึกผ่าน
 *    แลก: งานที่รถประกันผิดแล้วมีคู่กรณีจะไม่ถูกบังคับ หัวหน้าอาจต้องเติมเองตอนตรวจ
 */
check('มีตัวเดียวคุมเงื่อนไข ไม่กระจายซ้ำหลายที่',
      /bool _claimRequired\(\) => _faultIs\('คู่กรณีผิด'\) \|\| _faultIs\('ฝ่ายถูกและผิด'\);/.test(form));
check('ไม่ผูกกับ "มีคู่กรณีในหมวด 6" อีกแล้ว', !/_opponents\.isNotEmpty \|\| _faultIs/.test(form));
/** จุดแดงกับตัวตรวจก่อนส่งต้องใช้ตัวเดียวกัน ไม่งั้นช่างเจอ "ไม่ผ่าน" โดยไม่รู้ว่าช่องไหน */
const hits = (form.match(/_claimRequired\(\)/g) || []).length;
check('จุดแดง + ตัวตรวจก่อนส่ง เรียกตัวเดียวกัน', hits === 3, `เจอ ${hits} ที่ (นิยาม 1 + ใช้ 2)`);
check('หัวข้อรับ req เข้าไปจริง',
      /_fieldLabel\('การเรียกร้องค่าเสียหายจากคู่กรณี', req: _claimRequired\(\)\)/.test(form));

console.log('\n── ของเดิมที่ต้องไม่พังตาม ──');
/** "คู่กรณีคันที่" ผูกกับ 'คู่กรณีผิด' อย่างเดียว — ฝ่ายถูกและผิดไม่ต้องระบุคัน */
check('"คู่กรณีคันที่" ยังบังคับเฉพาะตอนคู่กรณีผิด',
      /if \(_faultIs\('คู่กรณีผิด'\)\)\s*\n\s*_numField\(_accFaultOpponentNoCtl/.test(form));
/** ตาข่ายรับค่าเก่าในฐานข้อมูล ('รถคู่กรณีเป็นฝ่ายผิด' มีจริง 1 ใบ) ต้องยังอยู่ */
check('ยังรับสำเนียงเก่าของค่าเดิมได้', /'คู่กรณีผิด': \['รถคู่กรณีเป็นฝ่ายผิด'\]/.test(form));
check('ตำรวจยังบังคับเฉพาะ "รอสรุปผลคดี"', /_faultIs\('รอสรุปผลคดี'\)/.test(form));

console.log(failed === 0 ? '\n✅ ผ่านทั้งหมด' : `\n❌ ไม่ผ่าน ${failed} ข้อ`);
process.exit(failed === 0 ? 0 : 1);
