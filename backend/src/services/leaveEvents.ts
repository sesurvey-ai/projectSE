import { getIO } from '../socket';

/**
 * แจ้งหน้าเว็บแอดมินว่า "ใบลาเปลี่ยนไปแล้ว" — หน้าใบลาจะโหลดใหม่เองโดยไม่ต้องกด F5
 *
 * ทำไมต้องมี: เดิมไม่มีสัญญาณอะไรเลย หัวหน้าต้องเปิด `/admin/leave` ไปกดดูเองเรื่อย ๆ
 * ว่ามีใครยื่นใบลาเข้ามาหรือยัง — ใบลาที่ยื่นเช้าอาจค้างถึงเย็นเพราะไม่มีใครรู้ว่ามี
 *
 * ⛔ เป็นแค่ "สัญญาณเตือน" ไม่ส่งข้อมูลใบลามาด้วย (เหตุผลการลาเป็นเรื่องส่วนตัว) —
 *    หน้าเว็บต้องไปดึงเองผ่าน API ปกติ ซึ่งตรวจสิทธิ์อยู่แล้ว
 *
 * ส่งเฉพาะห้อง `role:admin` เพราะอนุมัติลา = admin เท่านั้น (ตัดสินใจ 24/06/69)
 */
export type LeaveChangeReason =
  | 'created'    // พนักงานยื่นใบลาใหม่ (รออนุมัติ)
  | 'reviewed';  // แอดมินอนุมัติ/ไม่อนุมัติแล้ว — แท็บอื่นของแอดมินจะได้ไม่ค้างของเก่า

export function notifyLeaveChanged(reason: LeaveChangeReason, by?: number | null): void {
  const io = getIO();
  if (!io) return; // รันโหมดที่ไม่มี socket (เทส/สคริปต์) — ไม่ใช่เรื่องผิดปกติ
  io.to('role:admin').emit('leave_changed', { reason, by: by ?? null });
}
