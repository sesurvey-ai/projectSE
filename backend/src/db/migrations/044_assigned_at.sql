-- เวลาจ่ายงาน — ตัวตั้งต้นของ KPI ภายใน "งานควรเสร็จภายใน 24 ชม."
--
-- ทำไมต้องมีคอลัมน์ใหม่ ทั้งที่มีเวลาจ่ายงานอยู่แล้ว:
--   `survey_reports.acc_insurance_notify_date` เก็บเวลาจ่ายงานจริงก็จริง แต่เป็น **ข้อความ**
--   รูปแบบ 'D/M/พ.ศ.|HH:MM' เวลาไทย (ทำไว้ให้มือถือแสดงบนไทม์ไลน์) — ละเอียดแค่ระดับนาที
--   ไม่มีโซนเวลา และต้องแปลง พ.ศ. ก่อนคำนวณ · เอามาลบเวลาเพื่อวัด KPI = พังเงียบวันที่
--   รูปแบบเปลี่ยน · ตัวเลขเวลาควรเป็น timestamp จริง ไม่ใช่ข้อความสำหรับคนอ่าน
--
-- ⛔ งานเก่าที่จ่ายไปก่อนหน้านี้จะเป็น NULL — **ตั้งใจ ไม่ backfill**
--    เดาเวลาย้อนหลังจาก created_at ก็ได้ แต่จะได้ตัวเลข KPI ที่ดูเหมือนจริงทั้งที่มั่ว
--    หน้าเว็บถอยไปใช้ created_at แทนและบอกไว้ว่าเป็นค่าประมาณ (งานค้างจริงมีไม่กี่ใบ
--    เดี๋ยวก็หมุนไปเอง) · ไม่มีค่าปรับจากประกัน เป็น KPI ภายในล้วน (user ยืนยัน 31/08/69)
-- ⛔ **TIMESTAMPTZ ไม่ใช่ TIMESTAMP** — คอลัมน์เวลาอื่นในตารางนี้เป็นแบบไม่มีโซนเวลา
--    ซึ่ง node-postgres อ่านเป็น "เวลาเครื่องที่รัน" → เซิร์ฟเวอร์ไทย (+07) จะได้ค่าเพี้ยน
--    7 ชม. เงียบ ๆ (เจอจริงตอนเทส: ตั้งไว้ 26 ชม. หน้าเว็บโชว์ 33) · บน prod ที่เป็น UTC
--    บังเอิญถูก แต่พึ่งความบังเอิญไม่ได้ — ค่าที่ใช้ "ลบเวลา" ต้องผูกโซนเวลามาด้วยเสมอ
ALTER TABLE cases ADD COLUMN IF NOT EXISTS assigned_at TIMESTAMPTZ;
-- เผื่อกรณีเคยรันเวอร์ชันก่อนหน้าที่สร้างเป็น TIMESTAMP ไปแล้ว (ตีความค่าเดิมเป็น UTC)
ALTER TABLE cases ALTER COLUMN assigned_at TYPE TIMESTAMPTZ USING assigned_at AT TIME ZONE 'UTC';

COMMENT ON COLUMN cases.assigned_at IS
  'เวลาที่ callcenter กดมอบหมายงาน (UTC) — ตัวตั้งต้นนับ KPI 24 ชม. · NULL = จ่ายก่อนมีคอลัมน์นี้';
