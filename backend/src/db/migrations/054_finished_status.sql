-- 054: สถานะ "เสร็จงาน" (finished) — user สั่งทำ 07/09/69
--
-- ช่างกด "เสร็จงาน" ในแอปตอนเสร็จหน้างาน ก่อนออกจากที่เกิดเหตุ → assigned → finished
-- ยังไม่ใช่ "ส่งงาน": ฟอร์มยังแก้ต่อได้ (ที่บ้าน) แล้วค่อยส่งให้หัวหน้าตรวจ (finished → surveyed)
-- สิ่งที่ได้: บอร์ดจ่ายงานรู้ว่าช่างว่างแล้ว · หัวหน้าเห็น "เสร็จงานแล้ว รอส่งรายงาน" ·
-- เวลา "สำรวจเสร็จ" = เวลาที่กดจริง · ชื่อสถานะตรงกับ ISURVEY (ถึงที่ตรวจสอบ → เสร็จงาน → รอตรวจข้อมูล)
--
-- รันบน prod ด้วยมือ (ADD VALUE ของ enum ใช้ในทรานแซกชันเดียวกันไม่ได้ — รันไฟล์นี้ตรง ๆ ไม่ต้องครอบ BEGIN)
ALTER TYPE case_status ADD VALUE IF NOT EXISTS 'finished';
ALTER TABLE cases ADD COLUMN IF NOT EXISTS finished_at TIMESTAMPTZ;
COMMENT ON COLUMN cases.finished_at IS 'เวลาที่ช่างกด "เสร็จงาน" หน้างานในแอป — null = ยังไม่กด หรือส่งงานโดยไม่กด';
