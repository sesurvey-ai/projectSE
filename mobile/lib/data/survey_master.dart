// ── ตรวจ checksum เลขบัตรประชาชน (mod 11) ──
bool cidChecksum(String raw) {
  final d = raw.replaceAll(RegExp(r'\D'), '');
  if (d.length != 13) return false;
  var sum = 0;
  for (var i = 0; i < 12; i++) {
    sum += int.parse(d[i]) * (13 - i);
  }
  final check = (11 - (sum % 11)) % 10;
  return check == int.parse(d[12]);
}
