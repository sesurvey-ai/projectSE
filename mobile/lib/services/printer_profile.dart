/// สเปกที่ **ต่างกันจริงตามรุ่น** ของเครื่องพิมพ์พกพา — วัดจากเครื่องจริง ไม่ได้ถามจากตัวเครื่อง
///
/// ทำไมไม่ถามเครื่องเอา: ช่องทางที่เปิดไว้ **เขียนอย่างเดียว ไม่มีทางอ่านค่ากลับ** และเครื่องจีน
/// โหลส่วนใหญ่ก็ไม่ตอบคำสั่งถามสเปกของ TSPL (`~!@` / `~!F`) อยู่ดี — ลงแรงแล้วได้ไม่ครบทุกเครื่อง
/// จึงเก็บเป็นตารางที่วัดเอง · เครื่องที่ยังไม่เคยวัดตกไปใช้ [safe] ซึ่งช้าและเผื่อที่สุด
///
/// ⛔ เพิ่มเครื่องใหม่ = **วัดก่อนแล้วค่อยใส่ตาราง** อย่าเดาจากสเปกในกล่อง
///    (สเปก TSC เขียนว่ารองรับ ESC/POS ซึ่งของจริงไม่รองรับ — ดู PrintLang)
class PrinterProfile {
  const PrinterProfile({
    required this.label,
    required this.bandDots,
    required this.chunkBytes,
    required this.chunkGapMs,
    required this.bandGapMs,
    required this.tailPadDots,
  });

  /// ชื่อไว้โชว์ในบันทึกการทำงาน — จะได้รู้ว่าใบนี้พิมพ์ด้วยค่าชุดไหน
  final String label;

  /// ขนาดท่อน (จุด) — เพดานหน่วยความจำรับรูปต่อ 1 งานพิมพ์ · ต้องหารด้วย 8 ลงตัว
  final int bandDots;

  /// ส่งทีละกี่ไบต์ / เว้นกี่มิลลิวินาที = "เร็วสุดที่เครื่องรับไหวโดยไม่ขาด"
  final int chunkBytes;
  final int chunkGapMs;

  /// เว้นระหว่างท่อน — ให้เครื่องพิมพ์ท่อนก่อนหน้าจบก่อนค่อยยัดท่อนถัดไป
  final int bandGapMs;

  /// ขอบขาวท้ายใบ (จุด) — ชดเชยระยะหัวพิมพ์→ฟันฉีกซึ่งแต่ละรุ่นไม่เท่ากัน
  /// ตั้งให้ขอบบนใบที่ฉีกแล้วเท่ากันทุกเครื่อง โดยยึด PS-2472E9 เป็นตัวตั้ง (user เคาะ 03/09/69)
  final int tailPadDots;

  /// เครื่องที่ยังไม่เคยวัด — ช้าไว้ก่อน ท่อนเล็กไว้ก่อน ขอบเผื่อไว้ก่อน
  static const safe = PrinterProfile(
    label: 'ค่ากลาง (ยังไม่เคยวัด)',
    bandDots: 240,
    chunkBytes: 1024,
    chunkGapMs: 60,
    bandGapMs: 250,
    tailPadDots: 320,
  );

  /// TSC PS-2472E9 — บัฟเฟอร์ใหญ่สุดในบรรดาที่มี รับทั้งใบรวดเดียวมาตั้งแต่ ส.ค. 69
  /// จึงส่งท่อนเดียวจบและเร็วได้ · ขอบล่าง 240 = ใบที่ user บอกว่ากำลังดี (ตัวตั้งของรุ่นอื่น)
  static const ps2472 = PrinterProfile(
    label: 'PS-2472E9',
    bandDots: 2400,
    chunkBytes: 8192,
    chunkGapMs: 10,
    bandGapMs: 100,
    tailPadDots: 240,
  );

  /// BT-SPP — **ส่งทีเดียวจบ** เหมือน PS
  ///
  /// ที่เคยพิมพ์ออกแค่หัวกระดาษเมื่อ 27/08/69 เป็นเรื่อง **ความเร็ว ไม่ใช่หน่วยความจำ** —
  /// พอลดเป็น 1 KB/60 ms แล้วมันพิมพ์ทั้งใบรวดเดียวได้มาตลอด (ต่างจาก MHT-P29L ที่ตัน
  /// เพราะหน่วยความจำจริง ๆ) · หั่นท่อนกับเครื่องนี้จึงได้ผลข้างเคียงคือ **พิมพ์หยุดเป็นช่วง ๆ**
  /// ตรงรอยต่อท่อน (user ทัก 03/09/69) → กลับมาส่งท่อนเดียว แล้วคุมด้วยความเร็วแทน
  ///
  /// ⛔ 2 KB/30 ms คือจุดที่ยังไม่เคยเห็นขาด · เร่งเกินแล้วอาการเงียบมาก (ระบบบอกส่งครบ
  ///    แต่กระดาษขาดกลางใบ) — เจอเมื่อไหร่ให้ถอยเป็น chunkGapMs 60 ก่อน แล้วค่อยลด
  ///    bandDots ลงเป็น 720 ถ้ายังไม่หาย
  ///
  /// ขอบล่าง 200 = **น้อยกว่า PS** เพราะฟันฉีกอยู่ใกล้หัวพิมพ์กว่า (ที่ 280 แล้วเหลือเยอะไป)
  static const btSpp = PrinterProfile(
    label: 'BT-SPP',
    bandDots: 2400,
    chunkBytes: 2048,
    chunkGapMs: 30,
    bandGapMs: 120,
    tailPadDots: 200,
  );

  /// MHT-P29L — เครื่องเดียวที่ **หน่วยความจำตันจริง** ไม่ใช่เรื่องความเร็ว
  /// (ใบเต็ม 100 KB ไม่ออก · ใบย่อ 52 KB ก็ไม่ออก · ท่อน 11.6 KB ออกปกติ)
  /// จึงต้องหั่นท่อนต่อไป ต่างจาก PS/BT-SPP ที่ส่งทีเดียวจบได้
  ///
  /// ⛔ **240 จุด / 2 KB / 60 ms คือเพดานของเครื่องนี้ อย่าดันขึ้นอีก** —
  ///    ลองแล้วเมื่อ 03/09/69: ขยับเป็น 480 จุด (23 KB) พร้อมเร่งเป็น 4 KB/40 ms
  ///    → **พิมพ์ค้างกลางใบ** (ได้ถึงแค่ท่อนที่ 3 จาก 5) ต้องปิด-เปิดเครื่องแก้
  ///    ชุดค่านี้พิมพ์ครบมาแล้วหลายใบติดกัน จึงเป็นค่าที่ยึดไว้
  ///    (ถ้าจะลองใหม่ ให้ขยับ**ทีละค่า** ไม่ใช่ทั้งขนาดท่อนและความเร็วพร้อมกันแบบครั้งนั้น)
  ///
  /// ขอบล่าง 304 (38 มม.) — user เคาะ 03/09/69 หลังไล่ปรับ 320/360/336/240
  /// ⛔ เลขนี้มากกว่า PS (240) เพราะ **ฟันฉีกของรุ่นนี้อยู่ไกลจากหัวพิมพ์ที่สุด** —
  ///    ขอบที่วัดได้บนใบที่ฉีกแล้ว = ค่านี้ ลบ ระยะหัวพิมพ์→ฟันฉีกของเครื่อง
  ///    ตั้งเท่ากับ PS เมื่อไหร่จะได้ขอบจริงสั้นกว่า PS เสมอ
  static const mhtP29L = PrinterProfile(
    label: 'MHT-P29L',
    bandDots: 240,
    chunkBytes: 2048,
    chunkGapMs: 60,
    bandGapMs: 150,
    tailPadDots: 304,
  );

  /// MAC = ตัวเครื่องนั้น ๆ (ไม่ซ้ำแน่นอน) — จำเป็นกับเครื่องที่ชื่อโหลอย่าง 'BT-SPP'
  static const _byMac = <String, PrinterProfile>{
    'DC:0D:30:24:72:E9': ps2472,
    '00:19:0E:A6:48:15': btSpp,
    '66:32:22:AB:DC:4A': mhtP29L,
  };

  /// ชื่อ = รุ่น — ซื้อรุ่นเดิมเพิ่มก็ได้ค่าถูกต้องเอง ไม่ต้องมาเพิ่ม MAC ทีละตัว
  static const _byName = <String, PrinterProfile>{
    'PS-2472E9': ps2472,
    'MHT-P29L': mhtP29L,
  };

  /// ตัวเครื่องมาก่อนรุ่น แล้วค่อยตกไปที่ค่ากลาง
  static PrinterProfile of(String name, String mac) =>
      _byMac[mac.trim().toUpperCase()] ?? _byName[name.trim()] ?? safe;
}
